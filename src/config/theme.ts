export type MotionName = keyof typeof MOTION_MS;
export type OpacityName = keyof typeof OPACITY;

/** Farbe nach Tokenname; ein falscher Name ist ein Typfehler. */
export function themeColor(name: ColorName): ThemeColor {
  return COLORS[name];
}
